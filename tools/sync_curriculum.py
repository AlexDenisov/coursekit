#!/usr/bin/env python3
"""Validates curriculum.json and regenerates the files derived from it:

    docs/curriculum.js      the same data as a script, for docs/map.html
    docs/roadmap.md         exercise tables, by track and level
    docs/dependencies.md    the graph as Mermaid, plus the edge notes

    python3 tools/sync_curriculum.py           # validate + write
    python3 tools/sync_curriculum.py --check   # validate only; exit 1 if generated files are stale

Browsers don't let a page opened from file:// read a JSON file next to it, so
the map loads the data as a script instead. Run this after every change to
curriculum.json.

Checks: required fields, unique ids, known levels/tracks/domains, edges between
known exercises with known kinds, no cycles, the level rule (an exercise
depends only on exercises at its level or below), presets point at known
exercises/levels, the progress block is well-formed.
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "curriculum.json")
OUT_JS = os.path.join(ROOT, "docs", "curriculum.js")
OUT_ROADMAP = os.path.join(ROOT, "docs", "roadmap.md")
OUT_DEPS = os.path.join(ROOT, "docs", "dependencies.md")

EDGE_KINDS = {"req", "part", "real", "learn", "idea"}
COLORS = {f"--p{i}" for i in range(1, 11)}
ID_RE = re.compile(r"^[a-z0-9_]+(/[a-z0-9_]+)+$")


def check(c):
    errors = []
    for key in ("title", "levels", "tracks", "domains", "exercises", "edges"):
        if key not in c:
            errors.append(f"missing top-level key '{key}'")
    if errors:
        return errors

    p = c.get("progress", {})
    if not isinstance(p.get("runner", "command"), str) or not p.get("runner", "command").strip():
        errors.append('progress.runner must be "command", "bazel", or a shell command (your own runner)')

    levels = [l["id"] for l in c["levels"]]
    rank = {l: i for i, l in enumerate(levels)}
    domains = {d["id"] for d in c["domains"]}
    tracks = set()
    for t in c["tracks"]:
        tracks.add(t["id"])
        if t.get("color") not in COLORS:
            errors.append(f"track {t['id']}: color must be one of --p1..--p10")

    ex = {}
    for e in c["exercises"]:
        i = e.get("id", "?")
        for key in ("id", "title", "level", "tracks"):
            if key not in e:
                errors.append(f"{i}: missing '{key}'")
        if i in ex:
            errors.append(f"duplicate id {i}")
        ex[i] = e
        if not ID_RE.match(i):
            errors.append(f"{i}: ids are <domain>/<slug>, lowercase, digits and _ (no numbering)")
        if i.split("/")[0] not in domains:
            errors.append(f"{i}: unknown domain {i.split('/')[0]}")
        if e.get("level") not in rank:
            errors.append(f"{i}: unknown level {e.get('level')}")
        if not e.get("tracks"):
            errors.append(f"{i}: needs at least one track (the first is its main track)")
        for t in e.get("tracks", []):
            if t not in tracks:
                errors.append(f"{i}: unknown track {t}")
    if errors:
        return errors

    graph = {i: [] for i in ex}
    seen = set()
    for edge in c["edges"]:
        if len(edge) not in (3, 4):
            errors.append(f"edge {edge}: expected [from, to, kind, note?]")
            continue
        a, b, kind = edge[0], edge[1], edge[2]
        if a not in ex or b not in ex:
            errors.append(f"edge {a} -> {b}: unknown exercise")
            continue
        if kind not in EDGE_KINDS:
            errors.append(f"edge {a} -> {b}: unknown kind {kind} (one of {sorted(EDGE_KINDS)})")
        if (a, b) in seen:
            errors.append(f"edge {a} -> {b}: listed twice")
        seen.add((a, b))
        if rank[ex[a]["level"]] > rank[ex[b]["level"]]:
            errors.append(f"edge {a} -> {b}: a {ex[a]['level']} exercise before a {ex[b]['level']} one")
        graph[a].append(b)

    state = {}

    def dfs(u, path):
        state[u] = 1
        for v in graph[u]:
            if state.get(v) == 1:
                errors.append("cycle: " + " -> ".join(path + [u, v]))
            elif v not in state:
                dfs(v, path + [u])
        state[u] = 2

    for u in ex:
        if u not in state:
            dfs(u, [])

    for p in c.get("presets", []):
        for t in p.get("targets", []):
            if t not in ex:
                errors.append(f"preset {p.get('label')}: unknown target {t}")
        if "level" in p and p["level"] not in rank:
            errors.append(f"preset {p.get('label')}: unknown level {p['level']}")
        if not p.get("targets") and "level" not in p:
            errors.append(f"preset {p.get('label')}: needs targets or a level")
    return errors


def roadmap(c):
    out = ["# Roadmap", "",
           "Generated by `tools/sync_curriculum.py` from `curriculum.json`; don't edit.",
           "The interactive version, with dependencies, is [map.html](map.html).", "",
           "Exercises are listed under their main track; ★ marks milestones, *(given)* code you read",
           "rather than write.", ""]
    for t in c["tracks"]:
        mine = [e for e in c["exercises"] if e["tracks"][0] == t["id"]]
        goal = t.get("goal", "")
        out += [f"## {t['name']}", ""]
        if goal:
            out += [goal[0].upper() + goal[1:].rstrip(".") + ".", ""]
        if not mine:
            out += ["*Nothing here yet.*", ""]
        for lvl in c["levels"]:
            rows = [e for e in mine if e["level"] == lvl["id"]]
            if not rows:
                continue
            out += [f"**{lvl['name']}**", "", "| Exercise | | What |", "|---|---|---|"]
            for e in rows:
                name = ("★ " if e.get("milestone") else "") + e["title"] + (" *(given)*" if e.get("given") else "")
                out.append(f"| `{e['id']}` | {name} | {e.get('about', '')} |")
            out.append("")
    return "\n".join(out)


def dependencies(c):
    node = {e["id"]: f"n{i}" for i, e in enumerate(c["exercises"])}
    arrow = {"req": "-->", "part": "-.->", "real": "-.->", "learn": "==>"}
    out = ["# Dependencies", "",
           "Generated by `tools/sync_curriculum.py` from `curriculum.json`; don't edit.", "",
           "Edge kinds: `req` (solid: the tests call that code), `part` (dashed: one function",
           "or an optional part), `real` (dashed: only a real-data test or bench needs it),",
           "`learn` (thick: understand it first, no shared code), `idea` (background; listed below, not drawn).", "",
           "```mermaid", "flowchart LR"]
    for t in c["tracks"]:
        mine = [e for e in c["exercises"] if e["tracks"][0] == t["id"]]
        if not mine:
            continue
        out.append(f'  subgraph {t["id"]}["{t["name"]}"]')
        for e in mine:
            label = ("★ " if e.get("milestone") else "") + e["title"]
            out.append(f'    {node[e["id"]]}["{label.replace(chr(34), "")}<br/><small>{e["id"]}</small>"]')
        out.append("  end")
    for a, b, kind, *rest in c["edges"]:
        if kind == "idea":
            continue
        note = f"|{rest[0].replace('|', '/')}|" if rest and rest[0] else ""
        out.append(f"  {node[a]} {arrow[kind]}{note} {node[b]}")
    out += ["```", ""]
    ideas = [(a, b, rest[0] if rest else "") for a, b, kind, *rest in c["edges"] if kind == "idea"]
    if ideas:
        out += ["## Helpful background (not drawn)", "", "| For | Read first | Why |", "|---|---|---|"]
        out += [f"| `{b}` | `{a}` | {n} |" for a, b, n in ideas]
        out.append("")
    return "\n".join(out)


def main():
    raw = open(SRC, encoding="utf-8").read()
    try:
        c = json.loads(raw)
    except json.JSONDecodeError as e:
        sys.exit(f"curriculum.json is not valid JSON: {e}")
    errors = check(c)
    if errors:
        print("curriculum.json has problems:", *errors, sep="\n  ", file=sys.stderr)
        sys.exit(1)
    c["_hash"] = hashlib.sha1(raw.encode()).hexdigest()[:12]
    outputs = {
        OUT_JS: "// Written by tools/sync_curriculum.py from curriculum.json; don't edit.\n"
                "window.CURRICULUM = " + json.dumps(c, indent=1, ensure_ascii=False) + ";\n",
        OUT_ROADMAP: roadmap(c),
        OUT_DEPS: dependencies(c),
    }
    if "--check" in sys.argv[1:]:
        stale = [os.path.relpath(p, ROOT) for p, text in outputs.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != text]
        if stale:
            sys.exit("out of date (run python3 tools/sync_curriculum.py): " + ", ".join(stale))
        print("ok: curriculum.json is valid and the generated files are up to date")
        return
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"ok: {len(c['exercises'])} exercises, {len(c['edges'])} edges -> "
          "docs/curriculum.js, docs/roadmap.md, docs/dependencies.md")


if __name__ == "__main__":
    main()
