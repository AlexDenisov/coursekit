#!/usr/bin/env python3
"""Oracle for db/glob: which strings match which pattern, according to real Redis.

Stores every subject string as a key in a throwaway redis-server, asks
`KEYS <pattern>` for each pattern, and writes the full match table as C++:

    python3 tools/glob_reference.py > db/glob/redis_cases.inc

Patterns: hand-picked ones (one per rule) plus random ones over a small
alphabet full of special characters (seeded, so the output is reproducible).
"""

import random
import socket
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import redis_reference as ref  # noqa: E402

SUBJECTS = [
    "", "a", "b", "ab", "ba", "abc", "abcd", "aXc", "a-c", "a]c", "a[c", "a*c", "a?c",
    "a\\c", "hello", "hallo", "hxllo", "hllo", "heeeello", "user:1", "user:12", "user:",
    "^", "]", "[", "-", "*", "?", "\\", "a^", "AB", "Ab", "zebra", "abcabc", "aaa", "aaab",
]

# Not "*": KEYS * and SCAN without MATCH skip the matcher entirely (a fast path), so
# they'd report "" as matching, which stringmatchlen itself doesn't.
FIXED = [
    "a", "a*", "*c", "a*c", "*b*", "**", "a**c", "?", "??", "a?c", "h?llo", "h*llo",
    "h[ae]llo", "h[^e]llo", "h[a-b]llo", "h[b-a]llo", "a[]]c", "a[\\]]c", "a[\\-]c", "a[-]c",
    "a[a-]", "a[", "a[b", "a[^", "[^a]*", "a\\*c", "a\\?c", "a\\\\c", "a\\", "\\a", "[*]",
    "[?]", "[\\]", "[]", "[!a]*", "user:*", "user:?", "user:[0-9]*", "*:*", "a*a*a*",
    "*[", "[^]", "[a-c-e]*", "[A-Z]*", "ab*cd", "*abc", "abc*abc",
]


def random_patterns(n, seed=12345):
    rng = random.Random(seed)
    alphabet = "ab*?[]^-\\c"
    return ["".join(rng.choice(alphabet) for _ in range(rng.randint(1, 7))) for _ in range(n)]


def cpp(s):
    return ref.cpp(s.encode())


def main():
    proc, port = ref.start_server()
    try:
        sock = socket.create_connection(("127.0.0.1", port))
        rd = ref.Reader(sock)
        sock.sendall(ref.encode([b"FLUSHALL"])); rd.reply()
        for s in SUBJECTS:
            sock.sendall(ref.encode([b"SET", s.encode(), b"1"])); rd.reply()
        patterns = [p for p in dict.fromkeys(FIXED + random_patterns(400)) if p != "*"]
        print("// Generated by `python3 tools/glob_reference.py` from "
              + subprocess_version() + "; don't edit.")
        print("// {pattern, {subjects that match}}; the subjects are kSubjects.")
        print("inline const std::vector<std::string> kSubjects = {"
              + ", ".join(cpp(s) for s in SUBJECTS) + "};")
        print("inline const std::vector<std::pair<std::string, std::vector<std::string>>> kRedisCases = {")
        for p in patterns:
            sock.sendall(ref.encode([b"KEYS", p.encode()]))
            raw = rd.reply()
            matches = parse_array(raw)
            matches.sort(key=SUBJECTS.index)
            print(f"    {{{cpp(p)}, {{{', '.join(cpp(m) for m in matches)}}}}},")
        print("};")
    finally:
        proc.terminate()


def parse_array(raw):
    lines = raw.split(b"\r\n")
    n = int(lines[0][1:])
    out, i = [], 1
    for _ in range(n):
        out.append(lines[i + 1].decode())
        i += 2
    return out


def subprocess_version():
    import subprocess
    v = subprocess.run(["redis-server", "--version"], capture_output=True, text=True).stdout
    return v.split()[2]


if __name__ == "__main__":
    main()
